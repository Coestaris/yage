struct tm yage::core::get_time()
{
  time_t t = time(nullptr);
  return *localtime(&t);
}

float yage::core::get_ms()
{
  struct timespec ts;
  clock_gettime(CLOCK_MONOTONIC, &ts);
  return ts.tv_sec * 1000 + ts.tv_nsec / 1e6;
}